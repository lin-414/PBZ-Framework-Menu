# ABI export-table gate for build/PBZFM.dll.
#
# Rules:
#   - an export present in tests/abi/exports_baseline.txt but missing from the
#     DLL fails the check;
#   - a newly added export is allowed but printed as a WARNING so it stays
#     visible in review;
#   - any PBZFM_Test* / PBZFM_GetDemoButton export fails the check outright:
#     that DLL was built with PBZFM_TEST_HOOKS=ON and must never be shipped.
#
# -UpdateBaseline rewrites the baseline from the DLL, refusing to do so when
# test hooks are present (the baseline records the release/reference surface).
#
# Paths are resolved from the repository root (the parent of tools\), so the
# script works from any current directory.

param(
    [string]$DllPath = "",
    [string]$BaselinePath = "",
    [switch]$UpdateBaseline
)

$ErrorActionPreference = "Stop"

$repo = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($DllPath)) { $DllPath = "build/PBZFM.dll" }
if ([string]::IsNullOrWhiteSpace($BaselinePath)) { $BaselinePath = "tests/abi/exports_baseline.txt" }
if (-not [System.IO.Path]::IsPathRooted($DllPath)) { $DllPath = Join-Path $repo $DllPath }
if (-not [System.IO.Path]::IsPathRooted($BaselinePath)) { $BaselinePath = Join-Path $repo $BaselinePath }

if (-not (Test-Path $DllPath)) {
    Write-Host "[abi] FAIL: DLL not found: $DllPath"
    exit 1
}

function Find-Dumpbin {
    $cmd = Get-Command dumpbin.exe -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }

    $vswhere = Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"
    if (Test-Path $vswhere) {
        $roots = @(& $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath)
        foreach ($root in $roots) {
            if ([string]::IsNullOrWhiteSpace($root)) { continue }
            $tools = Join-Path $root "VC\Tools\MSVC"
            if (-not (Test-Path $tools)) { continue }
            $hit = Get-ChildItem $tools -Directory |
                Sort-Object Name -Descending |
                ForEach-Object { Join-Path $_.FullName "bin\Hostx64\x64\dumpbin.exe" } |
                Where-Object { Test-Path $_ } |
                Select-Object -First 1
            if ($hit) { return $hit }
        }
    }

    $hit = Get-ChildItem (Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\2022") -Directory -ErrorAction SilentlyContinue |
        ForEach-Object {
            $tools = Join-Path $_.FullName "VC\Tools\MSVC"
            if (Test-Path $tools) {
                Get-ChildItem $tools -Directory |
                    Sort-Object Name -Descending |
                    ForEach-Object { Join-Path $_.FullName "bin\Hostx64\x64\dumpbin.exe" }
            }
        } |
        Where-Object { Test-Path $_ } |
        Select-Object -First 1
    if ($hit) { return $hit }

    throw "dumpbin.exe not found (run from a VS developer shell or install VC tools)"
}

$dumpbin = Find-Dumpbin
$raw = & $dumpbin /nologo /exports $DllPath 2>&1
if ($LASTEXITCODE -ne 0) {
    Write-Host "[abi] FAIL: dumpbin /exports failed for $DllPath"
    exit 1
}

$names = @()
foreach ($line in $raw) {
    # Export table rows: ordinal  hint  RVA  name
    if ($line -match '^\s*\d+\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+(\S+)') {
        $names += $Matches[1]
    }
}
$names = @($names | Sort-Object -Unique)

if ($names.Count -eq 0) {
    Write-Host "[abi] FAIL: no exports parsed from $DllPath"
    exit 1
}

$hooks = @($names | Where-Object { $_ -match '^(PBZFM_Test[A-Za-z0-9_]*|PBZFM_GetDemoButton)$' })

if ($UpdateBaseline) {
    if ($hooks.Count -gt 0) {
        Write-Host "[abi] FAIL: refusing to write baseline from a test-hook DLL: $($hooks -join ', ')"
        exit 1
    }
    $header = @(
        "# PBZFM.dll export baseline (release build, PBZFM_TEST_HOOKS=OFF).",
        "# Generated by tools/check_abi_exports.ps1 -UpdateBaseline; names sorted."
    )
    $text = ($header + $names) -join "`n"
    [System.IO.File]::WriteAllText($BaselinePath, $text + "`n", (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "[abi] baseline written: $BaselinePath ($($names.Count) exports)"
    exit 0
}

if (-not (Test-Path $BaselinePath)) {
    Write-Host "[abi] FAIL: baseline not found: $BaselinePath"
    exit 1
}

$baseline = @(Get-Content $BaselinePath |
    ForEach-Object { $_.Trim() } |
    Where-Object { $_ -and (-not $_.StartsWith("#")) } |
    Sort-Object -Unique)

if ($baseline.Count -eq 0) {
    Write-Host "[abi] FAIL: baseline is empty: $BaselinePath"
    exit 1
}

$missing = @($baseline | Where-Object { $names -notcontains $_ })
# Test hooks are never a legitimate "allowed addition": report them as failures
# instead of as new-export warnings.
$added = @($names | Where-Object { ($baseline -notcontains $_) -and ($hooks -notcontains $_) })

$failed = $false

foreach ($name in $missing) {
    Write-Host "[abi] missing export: $name"
    $failed = $true
}
foreach ($name in $added) {
    Write-Host "[abi] WARNING new export: $name (append-only, update the baseline deliberately)"
}
foreach ($name in $hooks) {
    Write-Host "[abi] test hook exported: $name (PBZFM_TEST_HOOKS must be OFF for release)"
    $failed = $true
}

if ($failed) {
    Write-Host "[abi] FAIL: $($missing.Count) missing, $($hooks.Count) test hook(s); dll=$DllPath"
    exit 1
}

Write-Host "[abi] OK: $($names.Count) exports match baseline (missing=0, new=$($added.Count), test-hooks=0)"
exit 0
